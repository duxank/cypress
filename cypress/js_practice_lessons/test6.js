// String
let color = 'Yellow';
let lastName = 'Johnson';
console.log(color, lastName);

// Number
let length = 16;
let weight = 7.5;
console.log(length, weight);

// BigInt
let x = 1234567890123456789012345n;
let y = BigInt(1234567890123456789012345);
console.log(x, y);

// Boolean
let x1 = true;
let y1 = false;
console.log(x1, y1);

// Object
const person = { firstName: 'John', lastName: 'Doe' };
console.log(person);

// Array object
const cars = ['Saab', 'Volvo', 'BMW'];
console.log(cars);

// Date object
const date = new Date('2022-03-25');
console.log(date);

// Undefined
let x2;
let y2;
console.log(x2, y2);

// Null
let x3 = null;
let y3 = null;
console.log(x3, y3);

// Symbol
const x4 = Symbol();
const y4 = Symbol();
console.log(x4, y4);

typeof 'John Doe';
console.log(typeof 'John Doe');
